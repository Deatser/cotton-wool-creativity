# -*- coding: utf-8 -*-
"""Московское время.

Хостинг живёт по UTC, а заказчица и её покупатели по Москве. Из-за этого
в журнале действий и в заказах стояло время на три часа раньше настоящего:
сервер писал ISO-строку без пометки о поясе, а браузер потом читал её как
местное время и ничего не пересчитывал.

Москва с 2014 года круглый год UTC+3, переходов на летнее время нет,
поэтому достаточно постоянного сдвига и не нужна база часовых поясов.
"""
from datetime import datetime, timedelta, timezone

MSK = timezone(timedelta(hours=3))


def now():
    """Текущее московское время, без пометки о поясе.

    Пометку намеренно убираем: в таком виде время уже записано в заказах
    и в журнале, и в таком же виде его ждёт браузер. Смешивать записи
    с пометкой и без нельзя, иначе сравнение дат падает с ошибкой.
    """
    return datetime.now(MSK).replace(tzinfo=None)


def today():
    """Сегодняшняя дата по Москве."""
    return now().date()
